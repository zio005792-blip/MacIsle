//  In-memory clipboard history (never written to disk). Skips anything a password
//  manager marks as concealed or transient.
//

import AppKit
import Combine
import SwiftUI

struct ClipboardItem: Identifiable, Equatable {
    enum Content: Equatable {
        case text(String)
        case image(NSImage)
        case files([URL])
    }

    let id = UUID()
    let content: Content
    let date: Date
    let sourceBundleID: String?

    static func == (a: ClipboardItem, b: ClipboardItem) -> Bool { a.id == b.id }

    var preview: String {
        switch content {
        case .text(let s):
            return s.trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "\n", with: " ")
        case .image:
            return tr("图片", "Image")
        case .files(let urls):
            return urls.count == 1 ? urls[0].lastPathComponent : tr("\(urls.count) 个文件", "\(urls.count) files")
        }
    }

    var symbol: String {
        switch content {
        case .text(let s):
            if let url = URL(string: s.trimmingCharacters(in: .whitespacesAndNewlines)),
               url.scheme?.hasPrefix("http") == true { return "link" }
            return "text.alignleft"
        case .image: return "photo"
        case .files: return "doc"
        }
    }
}

@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()

    @Published private(set) var items: [ClipboardItem] = []
    @AppStorage("island.clipboard.enabled") var isEnabled: Bool = true {
        didSet { isEnabled ? start() : stop() }
    }

    private let limit = 24
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var ignoreChangeCount: Int?
    private var timer: AnyCancellable?

    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.apple.is-remote-clipboard"
    ]

    private init() {
        if isEnabled { start() }
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.publish(every: 0.7, on: .main, in: .common)
            .autoconnect()
            .sink { [weak self] _ in
                Task { @MainActor in self?.poll() }
            }
    }

    func stop() {
        timer = nil
    }

    func clear() {
        items.removeAll()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
    }

    /// Puts an item back on the pasteboard and moves it to the top.
    func copy(_ item: ClipboardItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.content {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let img): pb.writeObjects([img])
        case .files(let urls): pb.writeObjects(urls as [NSURL])
        }
        ignoreChangeCount = pb.changeCount
        lastChangeCount = pb.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(ClipboardItem(content: item.content, date: .now, sourceBundleID: item.sourceBundleID), at: 0)
        IslandUIState.shared.flash(.copied(item.preview), duration: 1.6)
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        if ignoreChangeCount == pb.changeCount { return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }

        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        var content: ClipboardItem.Content?

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            content = .files(urls)
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            content = .text(String(s.prefix(20_000)))
        } else if let img = NSImage(pasteboard: pb) {
            content = .image(img)
        }
        guard let content else { return }

        if let first = items.first, first.content == content { return }
        items.removeAll { $0.content == content }
        items.insert(ClipboardItem(content: content, date: .now, sourceBundleID: source), at: 0)
        if items.count > limit { items.removeLast(items.count - limit) }
    }
}
